// PROMPT FRAMEWORK của RusWrite AI.
//
// Không còn system prompt kiểu "Bạn là giáo viên tiếng Nga B1".
// Mỗi lần gọi model, prompt được LẮP từ các khối độc lập:
//
//   BASE ROLE + LEVEL RULES + RUBRIC RULES + TOPIC + OUTLINE + VOCABULARY
//   + ESSAY + ANTI-HALLUCINATION + ANTI-OVERCORRECTION + OUTPUT RULES
//
// Cùng một khung, nhưng khối LEVEL RULES lấy từ levelProfiles.js nên A1 và C1
// nhận được hai bộ chỉ dẫn khác hẳn nhau.
