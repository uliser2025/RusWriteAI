function buildOutlinePrompt({ level, topic }) {
    const p = getProfile(level);
    return [
        baseRole('outline'),
        block('ЯЗЫК ОТВЕТА', languagePolicy(p)),
        block('УРОВЕНЬ И ЕГО ПРАВИЛА', levelRules(p, 'outline')),
        block('ТЕМА', topicContext(topic)),
        block('ЧТО ТАКОЕ ХОРОШИЙ ПЛАН', `План должен быть таким, чтобы по нему МОЖНО БЫЛО НАПИСАТЬ ТЕКСТ.
Отдельные слова («природа», «государство», «будущее») планом НЕ являются — это запрещено.
Каждый подпункт — законченная мысль о том, что писать: «причины загрязнения воздуха в больших городах»,
а не «загрязнение». Это касается КАЖДОГО пункта без исключения — введения, заключения и подпунктов
основной части: местоимение или одно слово («Я», «Семья») никогда не является отдельным пунктом плана,
даже на уровне A1. Минимум ${p.code === 'A1' || p.code === 'A2' ? '2' : '3'} слова на пункт.

При этом ты НЕ пишешь сочинение за студента:
- никаких готовых абзацев;
- речевые образцы (speech_patterns) — только короткие клише-заготовки для введения, перехода и заключения.`),
        block('СЛОВАРНЫЙ ЗАПАС К ЭТОМУ ПЛАНУ', `Лексика подбирается ПОД ЭТУ ТЕМУ И ПОД ЭТОТ ПЛАН, а не «вообще полезные слова».
Для каждой единицы поле section_ref указывает, в какой части плана она понадобится,
а relevance_ru объясняет по-русски, какую мысль она помогает выразить.
Предпочитай устойчивые словосочетания одиночным словам: они сразу дают студенту готовый строительный блок.
Не усложняй ради «солидности» — каждая единица должна реально пригодиться в этом сочинении.`),
        block('ГРАММАТИКА К ЭТОМУ ПЛАНУ', `2–4 конструкции, которые естественно нужны именно для этой темы и этого уровня.
example_ru — короткий пример ПО ТЕМЕ сочинения, а не абстрактный.`),
        block('ЗАПРЕТЫ', ANTI_HALLUCINATION),
        block('ФОРМАТ', 'Верни ТОЛЬКО JSON по заданной схеме. Никакого текста до или после JSON.')
    ].filter(Boolean).join('');
}

function buildCorrectPrompt({ level, rubric, topic, outline, vocabulary }) {
    const p = getProfile(level);
    return [
        baseRole('correct'),
        block('ЯЗЫК ОТВЕТА — ЧИТАЙ ВНИМАТЕЛЬНО', correctionLanguagePolicy(p)),
        block('УРОВЕНЬ CEFR — ГЛАВНАЯ СИСТЕМА ОТСЧЁТА', cefrPolicy(p)),
        block('УРОВЕНЬ И ЕГО ПРАВИЛА', levelRules(p, 'correct')),
        block('КРИТЕРИИ ОЦЕНИВАНИЯ (ТРКИ)', rubricRules(rubric)),
        block('ТЕМА', topicContext(topic)),
        block('ПЛАН, ПО КОТОРОМУ ПИСАЛ СТУДЕНТ', outlineContext(outline)),
        block('ВЫДАННЫЙ СЛОВАРНЫЙ ЗАПАС', vocabularyContext(vocabulary)),
        block('КАЧЕСТВО ОБЪЯСНЕНИЙ', EXPLANATION_QUALITY),
        block('НЕ ИСПРАВЛЯЙ ЛИШНЕГО', ANTI_OVERCORRECTION),
        block('НЕ ВЫДУМЫВАЙ', ANTI_HALLUCINATION),
        block('СТРУКТУРА ОТЗЫВА', `overall_feedback_vi — общее впечатление ПО-ВЬЕТНАМСКИ (3–5 предложений, с опорой на текст).
main_problem_vi — ОДНА главная проблема, которая сильнее всего мешает тексту, по-вьетнамски.
strengths_vi — что уже получается (только то, что реально есть в тексте), по-вьетнамски.
weaknesses_vi — что мешает тексту быть сильнее, по-вьетнамски.
next_steps_vi — конкретные шаги по порядку важности, а не общие советы, по-вьетнамски.
vocabulary_to_improve_ru — список САМИХ РУССКИХ единиц для повторения (по-русски).
grammar_to_improve_vi — названия грамматических тем по-вьетнамски, русский термин можно
дать в скобках: «Cách 4 với động từ chỉ tác động (винительный падеж)».
recommended_vocabulary — те единицы, которых студенту НЕ ХВАТИЛО: если он написал
«много мусора», покажи «большое количество отходов» / «сократить количество отходов»
и объясни в relevance_ru (по-русски), почему так естественнее в письменной речи.
level_position_vi — по-вьетнамски; обязательно назови уровень ${level} явно и скажи,
что отделяет этот текст от уверенного ${level}.`),
        block('ФОРМАТ', 'Верни ТОЛЬКО JSON по заданной схеме. Никакого текста до или после JSON.')
    ].filter(Boolean).join('');
}

function buildVocabDetailPrompt({ level, topic, term, essay, context }) {
    const p = getProfile(level);
    return [
        baseRole('vocab'),
        block('ЯЗЫК ОТВЕТА', languagePolicy(p)),
        block('УРОВЕНЬ И ЕГО ПРАВИЛА', levelRules(p, 'vocab')),
        block('ТЕМА СОЧИНЕНИЯ', topicContext(topic)),
        block('ПОЧЕМУ ЭТО СЛОВО ПОЯВИЛОСЬ', context
            ? `Единица была предложена студенту с таким обоснованием: «${context}».
Разверни это обоснование в поле why_relevant_ru, не противореча ему.`
            : 'Обоснование не передано — сформулируй его сам, опираясь на тему сочинения.'),
        block('ТЕКСТ СТУДЕНТА', essay
            ? `Вот что студент уже написал. Если единица в тексте встречается — оцени, уместно ли;
если нет — покажи, в каком месте она была бы к месту:\n\n${String(essay).slice(0, 3000)}`
            : 'Текста ещё нет — студент только готовится писать.'),
        block('ЧЕГО НЕЛЬЗЯ ДЕЛАТЬ', `Это НЕ словарная статья вообще. Это карточка для КОНКРЕТНОГО сочинения
конкретного студента уровня ${level}.
- Не давай значений, не имеющих отношения к этой теме.
- Обязательно ставь ударение в поле pronunciation (знак ́ после ударной гласной: защища́ть).
- Примеры пиши по теме сочинения, а не абстрактные.`),
        block('ФОРМАТ', 'Верни ТОЛЬКО JSON по заданной схеме. Никакого текста до или после JSON.')
    ].filter(Boolean).join('');
}

module.exports = { buildOutlinePrompt, buildCorrectPrompt, buildVocabDetailPrompt, rubricRules, levelRules, cefrPolicy, correctionLanguagePolicy };
