// KHỐI 5 — NGỮ CẢNH HỌC TẬP (learningContext)
// --------------------------------------------------------------------------
function topicContext(topic) {
    if (!topic || !topic.prompt) return 'Тема студентом не выбрана — ориентируйся только на сам текст.';
    return `Название: ${topic.title || '(без названия)'}
Формулировка задания: ${topic.prompt}`;
}

function outlineContext(outline) {
    if (!outline || !outline.outline) {
        return `Студент НЕ запрашивал план перед написанием.
Поэтому outline_coverage должен быть ПУСТЫМ массивом. Не придумывай план, которого не было.`;
    }
    const o = outline.outline;
    const body = (o.body || []).map((s, i) => `${i + 1}. ${s.heading_ru}\n${(s.points || []).map(p => `   - ${p}`).join('\n')}`).join('\n');
    return `Студент писал текст ПО ЭТОМУ ПЛАНУ, который ты сам ему выдал:

Введение:
${(o.introduction || []).map(x => `   - ${x}`).join('\n')}

Основная часть:
${body}

Заключение:
${(o.conclusion || []).map(x => `   - ${x}`).join('\n')}

В отзыве обязательно соотнеси текст с планом: что раскрыто, что раскрыто частично,
что осталось только в плане. Заполни outline_coverage по пунктам ЭТОГО плана.`;
}

function vocabularyContext(vocabulary) {
    if (!Array.isArray(vocabulary) || !vocabulary.length) {
        return `Словарного запаса к этой работе не выдавалось — vocabulary_usage оставь пустым массивом.`;
    }
    return `Вместе с планом студент получил такой словарный запас:
${vocabulary.map(v => `- ${v.term} (${v.difficulty || '?'})`).join('\n')}

Проверь по тексту, какие из этих единиц студент реально употребил и насколько уместно.
Заполни vocabulary_usage. Не утверждай, что слово использовано, если его в тексте нет.`;
}

