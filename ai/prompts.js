// KHỐI 3 — QUY TẮC THEO TRÌNH ĐỘ (trái tim của nguyên tắc LEVEL-FIRST)
// --------------------------------------------------------------------------
function levelRules(profile, task) {
    const common = `УРОВЕНЬ СТУДЕНТА: ${profile.code} (${profile.trki}).
${profile.description_ru}

ЯЗЫКОВОЙ ПРОФИЛЬ УРОВНЯ — не выходи за эти рамки, когда что-то предлагаешь студенту:
${profile.languageProfile_ru.map(x => `- ${x}`).join('\n')}`;

    if (task === 'outline') {
        return `${common}

КАК СТРОИТЬ ПЛАН НА ЭТОМ УРОВНЕ:
${profile.outline.style_ru}
- Основная часть: примерно ${profile.outline.bodySections} смысловые части, в каждой ${profile.outline.bulletsPerSection} подпункта.
- Ожидаемый объём будущего сочинения: ${profile.outline.expectedLength_ru}.

ЛЕКСИКА ДЛЯ ЭТОГО УРОВНЯ:
- Примерно ${profile.vocabulary.count} единиц.
- ${profile.vocabulary.mix_ru}
- Допустимые значения поля difficulty: ${profile.vocabulary.allowedDifficulty.join(', ')} — другие значения запрещены.
- ${profile.upgradePolicy_ru}`;
    }

    if (task === 'correct') {
        return `${common}

КАК ОБЪЯСНЯТЬ ОШИБКИ НА ЭТОМ УРОВНЕ:
${profile.explanationStyle_ru}

КАК ПИСАТЬ ОТЗЫВ НА ЭТОМ УРОВНЕ:
${profile.feedbackStyle_ru}

ЧТО СЧИТАТЬ УЛУЧШЕНИЕМ НА ЭТОМ УРОВНЕ:
${profile.upgradePolicy_ru}

РЕКОМЕНДУЕМАЯ ЛЕКСИКА (recommended_vocabulary):
- ${profile.vocabulary.mix_ru}
- Допустимые значения difficulty: ${profile.vocabulary.allowedDifficulty.join(', ')}.`;
    }

    // vocab
    return `${common}

КАК ОБЪЯСНЯТЬ СЛОВО НА ЭТОМ УРОВНЕ:
${profile.explanationStyle_ru}
Толкование (meaning_ru) должно состоять из слов, понятных на уровне ${profile.code}.
Примеры должны быть такими, чтобы студент уровня ${profile.code} мог сам написать похожее предложение.`;
}

// --------------------------------------------------------------------------
// KHỐI 3b — RÀNG BUỘC CEFR (mục IV)
//
// Trình độ không được chỉ là một dropdown. Khối này biến nó thành thước đo:
// AI phải chấm bài SO VỚI bậc đã chọn, không phải so với tiếng Nga hoàn hảo.
// Đây là nguồn gốc của lỗi "bài A2 bị chấm theo chuẩn C1" mà bạn gặp.
// --------------------------------------------------------------------------
function cefrPolicy(profile) {
    const higher = { A1: 'A2 и выше', A2: 'B1 и выше', B1: 'B2 и выше', B2: 'C1 и выше', C1: 'C2', C2: '—' }[profile.code];
    return `Заявленный уровень студента: ${profile.code} (${profile.trki}).
Ты оцениваешь текст ОТНОСИТЕЛЬНО ЭТОГО УРОВНЯ, а не относительно идеального русского языка
и не относительно уровня носителя.

ЧТО ЭТО ЗНАЧИТ НА ПРАКТИКЕ:
1. Ошибка — это нарушение того, что студент уровня ${profile.code} УЖЕ ДОЛЖЕН уметь.
   Конструкция уровня ${higher}, которой в тексте просто НЕТ, — это не ошибка.
   Не снимай баллы за отсутствие того, что на этом уровне ещё не требуется.
2. Простота ≠ слабость. Если на уровне ${profile.code} простое предложение уместно и корректно,
   оно ОЦЕНИВАЕТСЯ ПОЛОЖИТЕЛЬНО, а не как «бедный синтаксис».
3. Все твои предложения — исправления, upgrades, recommended_vocabulary, next_steps_vi —
   должны оставаться в пределах ${profile.code}, максимум на полшага выше.
   Предлагать студенту ${profile.code} конструкции уровня ${higher} — методическая ошибка.
4. Оценка лексики, грамматики, сложности и связности ведётся по нормам ${profile.code}.
5. В level_position_vi назови уровень ${profile.code} явно и скажи по-вьетнамски,
   чего конкретно не хватает до уверенного ${profile.code}, а не до «хорошего русского».

ЯЗЫКОВОЙ ПОТОЛОК УРОВНЯ ${profile.code} — ориентир для всех твоих рекомендаций:
${profile.languageProfile_ru.map(x => `- ${x}`).join('\n')}`;
}

