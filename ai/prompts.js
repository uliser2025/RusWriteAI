const { getProfile } = require('./levelProfiles');

const line = '—'.repeat(60);
function block(title, body) {
    if (!body || !String(body).trim()) return '';
    return `\n${line}\n### ${title}\n${line}\n${body}\n`;
}

// --------------------------------------------------------------------------
// KHỐI 1 — VAI TRÒ NỀN
// --------------------------------------------------------------------------
function baseRole(task) {
    const tasks = {
        outline: 'составить учебный ПЛАН сочинения',
        correct: 'проверить сочинение, разобрать ошибки и дать развёрнутый отзыв',
        vocab: 'подготовить учебную словарную карточку'
    };
    return `Ты — опытный преподаватель русского языка как иностранного (РКИ) и эксперт-экзаменатор ТРКИ/TORFL.
Твои студенты — вьетнамцы, которые учатся писать по-русски.
Твоя задача в этом запросе: ${tasks[task]}.

Ты работаешь не как «проверялка», а как наставник: всё, что ты даёшь, должно быть встроено
в один учебный маршрут: УРОВЕНЬ → ТЕМА → ПЛАН → ЛЕКСИКА И ГРАММАТИКА → ТЕКСТ →
РАЗБОР → ИСПРАВЛЕНИЯ → ОТЗЫВ → СЛЕДУЮЩИЕ ШАГИ.`;
}

// --------------------------------------------------------------------------
// KHỐI 2 — QUY TẮC NGÔN NGỮ ĐẦU RA (mục 2 trong yêu cầu)
// --------------------------------------------------------------------------
function languagePolicy(profile) {
    return `Весь учебный контент пиши ПО-РУССКИ: пункты плана, объяснения ошибок, правила,
отзыв, значения слов, примеры. Это принципиальное требование — вьетнамский язык
в этих полях НЕ допускается.

${profile.needViGloss
            ? `Уровень ${profile.code} ещё не читает свободно по-русски, поэтому:
- русский текст должен быть максимально простым (см. языковой профиль ниже);
- дополнительно заполняй короткие поля-подсказки на вьетнамском (meaning_vi, vi_gloss) — одна строка, не перевод всего объяснения.`
            : `Поля meaning_vi заполняй одним-двумя вьетнамскими словами (только для сверки).
Поле vi_gloss на этом уровне оставляй пустой строкой.`}`;
}

// --------------------------------------------------------------------------
// KHỐI 3 — QUY TẮC THEO TRÌNH ĐỘ (trái tim của nguyên tắc LEVEL-FIRST)
// --------------------------------------------------------------------------
function levelRules(profile, task) {
    const common = `УРОВЕНЬ СТУДЕНТА: ${profile.code} (${profile.trki}).
${profile.description_ru}

ЯЗЫКОВОЙ ПРОФИЛЬ УРОВНЯ — не выходи за эти рамки, когда что-то предлагаешь студенту:
${profile.languageProfile_ru.map(x => `- ${x}`).join('\n')}`;

    if (task === 'outline') {
        return `${common}

КАК СТРОИТЬ ПЛАН НА ЭТОМ УРОВНЕ:
${profile.outline.style_ru}
- Основная часть: примерно ${profile.outline.bodySections} смысловые части, в каждой ${profile.outline.bulletsPerSection} подпункта.
- Ожидаемый объём будущего сочинения: ${profile.outline.expectedLength_ru}.

ЛЕКСИКА ДЛЯ ЭТОГО УРОВНЯ:
- Примерно ${profile.vocabulary.count} единиц.
- ${profile.vocabulary.mix_ru}
- Допустимые значения поля difficulty: ${profile.vocabulary.allowedDifficulty.join(', ')} — другие значения запрещены.
- ${profile.upgradePolicy_ru}`;
    }

    if (task === 'correct') {
        return `${common}

КАК ОБЪЯСНЯТЬ ОШИБКИ НА ЭТОМ УРОВНЕ:
${profile.explanationStyle_ru}

КАК ПИСАТЬ ОТЗЫВ НА ЭТОМ УРОВНЕ:
${profile.feedbackStyle_ru}

ЧТО СЧИТАТЬ УЛУЧШЕНИЕМ НА ЭТОМ УРОВНЕ:
${profile.upgradePolicy_ru}

РЕКОМЕНДУЕМАЯ ЛЕКСИКА (recommended_vocabulary):
- ${profile.vocabulary.mix_ru}
- Допустимые значения difficulty: ${profile.vocabulary.allowedDifficulty.join(', ')}.`;
    }

    // vocab
    return `${common}

КАК ОБЪЯСНЯТЬ СЛОВО НА ЭТОМ УРОВНЕ:
${profile.explanationStyle_ru}
Толкование (meaning_ru) должно состоять из слов, понятных на уровне ${profile.code}.
Примеры должны быть такими, чтобы студент уровня ${profile.code} мог сам написать похожее предложение.`;
}

// --------------------------------------------------------------------------
// KHỐI 4 — QUY TẮC RUBRIC ТРКИ (giữ nguyên logic chấm điểm cũ)
// --------------------------------------------------------------------------
function rubricRules(rubric) {
    if (!rubric) {
        return `Для этого уровня официальная шкала ТРКИ в базе не найдена.
Не выдумывай шкалу: поля parameter_scores и bonus_awarded оставь пустыми/нулевыми,
а качество текста опиши словами в отзыве.`;
    }

    const head = `Оценивание идёт по шкале ${rubric.trkiName}.
Источник критериев (заявленная надёжность: ${rubric.sourceConfidence}): ${rubric.source}
Не объявляй «официальным» ничего, чего нет в этом описании.

КЛАССИФИКАЦИЯ ОШИБОК ТРКИ — это единственная классификация, которую ты используешь в поле error_class:
- «КЗО» — коммуникативно значимая ошибка: обычный носитель русского языка (НЕ преподаватель,
  привыкший к речи иностранцев) поймёт фразу неправильно или не поймёт вообще.
- «КНЗО» — коммуникативно незначимая ошибка: нарушение нормы есть, но смысл понятен верно.`;

    if (rubric.scoringMethod === 'deduction') {
        const extra = (rubric.deductionRules?.taskCriteria || []).map(t => `- ${t}`).join('\n');
        const bonus = rubric.deductionRules?.bonusRules
            ? `Бонус: ${rubric.deductionRules.bonusRules.description}. Поле bonus_awarded — от 0 до ${rubric.deductionRules.bonusRules.maxBonus}, с обоснованием в bonus_reason_ru.`
            : 'На этом уровне бонусных баллов НЕТ: bonus_awarded = 0, bonus_reason_ru = "".';
        return `${head}

МЕХАНИЗМ: прямое снятие баллов со шкалы ${rubric.totalScore} баллов.
Ты НЕ считаешь баллы сам — систему подсчёта выполняет сервер
(каждая КЗО −${rubric.deductionRules.kzoPenalty}, каждая КНЗО −${rubric.deductionRules.knzoPenalty}).
Твоя работа — правильно классифицировать каждую ошибку.
${extra ? `\nДополнительные требования ${rubric.trkiName}:\n${extra}` : ''}
${bonus}
parameter_scores на этом уровне оставь пустым массивом.`;
    }

    const params = rubric.parameters.map(p => `- ${p.name} (0–${p.maxScore}): ${p.description}`).join('\n');
    const reqs = (rubric.essayRequirements || []).length
        ? `\nОБЯЗАТЕЛЬНЫЕ СОДЕРЖАТЕЛЬНЫЕ КОМПОНЕНТЫ ЭССЕ — проверь каждый и заполни essay_requirements_check:\n${rubric.essayRequirements.map(r => `- ${r}`).join('\n')}`
        : '\nessay_requirements_check оставь пустым массивом.';
    return `${head}

МЕХАНИЗМ: оценка по параметрам. Выстави «сырой» балл каждому параметру:
${params}
Ограничение баллов при наличии КЗО применяет сервер — ты его НЕ применяешь.
bonus_awarded = 0, bonus_reason_ru = "".${reqs}`;
}

// --------------------------------------------------------------------------
// KHỐI 5 — NGỮ CẢNH HỌC TẬP (learningContext)
// --------------------------------------------------------------------------
function topicContext(topic) {
    if (!topic || !topic.prompt) return 'Тема студентом не выбрана — ориентируйся только на сам текст.';
    return `Название: ${topic.title || '(без названия)'}
Формулировка задания: ${topic.prompt}`;
}

function outlineContext(outline) {
    if (!outline || !outline.outline) {
        return `Студент НЕ запрашивал план перед написанием.
Поэтому outline_coverage должен быть ПУСТЫМ массивом. Не придумывай план, которого не было.`;
    }
    const o = outline.outline;
    const body = (o.body || []).map((s, i) => `${i + 1}. ${s.heading_ru}\n${(s.points || []).map(p => `   - ${p}`).join('\n')}`).join('\n');
    return `Студент писал текст ПО ЭТОМУ ПЛАНУ, который ты сам ему выдал:

Введение:
${(o.introduction || []).map(x => `   - ${x}`).join('\n')}

Основная часть:
${body}

Заключение:
${(o.conclusion || []).map(x => `   - ${x}`).join('\n')}

В отзыве обязательно соотнеси текст с планом: что раскрыто, что раскрыто частично,
что осталось только в плане. Заполни outline_coverage по пунктам ЭТОГО плана.`;
}

function vocabularyContext(vocabulary) {
    if (!Array.isArray(vocabulary) || !vocabulary.length) {
        return `Словарного запаса к этой работе не выдавалось — vocabulary_usage оставь пустым массивом.`;
    }
    return `Вместе с планом студент получил такой словарный запас:
${vocabulary.map(v => `- ${v.term} (${v.difficulty || '?'})`).join('\n')}

Проверь по тексту, какие из этих единиц студент реально употребил и насколько уместно.
Заполни vocabulary_usage. Не утверждай, что слово использовано, если его в тексте нет.`;
}

// --------------------------------------------------------------------------
// KHỐI 6 — CHỐNG BỊA & CHỐNG SỬA QUÁ TAY (mục 21, 22, 9)
// --------------------------------------------------------------------------
const ANTI_HALLUCINATION = `1. Каждое утверждение об этом студенте должно опираться на ЕГО текст.
   Никогда не пиши «вы правильно использовали X», если X в тексте нет.
2. Поле original в каждой ошибке — это ДОСЛОВНЫЙ фрагмент из текста студента.
   Не перефразируй его и не «чинь» заранее.
3. Если чего-то в тексте нет (аргумента, примера, вывода) — так и пиши: этого нет.
   Отсутствие — это тоже честная обратная связь.
4. Не ссылайся на источники, документы или правила, которых нет в этом запросе.`;

const ANTI_OVERCORRECTION = `1. Если предложение ГРАММАТИЧЕСКИ И ЛЕКСИЧЕСКИ КОРРЕКТНО — оставь его в corrected_text
   БЕЗ ИЗМЕНЕНИЙ. Даже если тебе кажется, что можно «красивее».
2. Разделяй строго:
   - errors[]   — нарушение нормы. Только это влияет на оценку.
   - upgrades[] — корректно, но может быть лучше. На оценку НЕ влияет никогда.
3. Тип улучшения указывай честно в upgrade_type:
   «более естественно» / «более формально» / «более точно» / «слишком разговорно» / «более книжно».
4. Не превращай текст уровня A1/B1 в текст уровня C1. Предложенный вариант должен
   оставаться в пределах уровня студента (максимум на полшага выше).
5. Если улучшение не даёт заметного выигрыша — не предлагай его вообще.
   Пустой массив upgrades лучше, чем список придирок.`;

// --------------------------------------------------------------------------
// KHỐI 7 — CHẤT LƯỢNG GIẢI THÍCH (mục 8, 10)
// --------------------------------------------------------------------------
const EXPLANATION_QUALITY = `Объяснение ошибки НИКОГДА не сводится к «правильно так».
Минимальная структура каждого explanation_ru:
  (1) что именно нарушено (правило/управление/согласование/вид/порядок слов);
  (2) почему в ЭТОМ контексте нужен именно такой вариант;
  (3) короткий правильный пример по теме сочинения.
rule_tip_ru — это отдельная короткая формула-памятка, которую студент может запомнить
(например: «защищать + кого? что? → винительный падеж»).

Отзыв (overall_feedback_ru и списки) тоже не может быть общим. Запрещены формулировки
вроде «текст хороший, но есть ошибки». Каждый пункт должен опираться на конкретное место текста.`;

