// KHỐI 4 — QUY TẮC RUBRIC ТРКИ (giữ nguyên logic chấm điểm cũ)
// --------------------------------------------------------------------------
function rubricRules(rubric) {
    if (!rubric) {
        return `Для этого уровня официальная шкала ТРКИ в базе не найдена.
Не выдумывай шкалу: поля parameter_scores и bonus_awarded оставь пустыми/нулевыми,
а качество текста опиши словами в отзыве.`;
    }

    const head = `Оценивание идёт по шкале ${rubric.trkiName}.
Источник критериев (заявленная надёжность: ${rubric.sourceConfidence}): ${rubric.source}
Не объявляй «официальным» ничего, чего нет в этом описании.

КЛАССИФИКАЦИЯ ОШИБОК ТРКИ — это единственная классификация, которую ты используешь в поле error_class:
- «КЗО» — коммуникативно значимая ошибка: обычный носитель русского языка (НЕ преподаватель,
  привыкший к речи иностранцев) поймёт фразу неправильно или не поймёт вообще.
- «КНЗО» — коммуникативно незначимая ошибка: нарушение нормы есть, но смысл понятен верно.`;

    if (rubric.scoringMethod === 'deduction') {
        const extra = (rubric.deductionRules?.taskCriteria || []).map(t => `- ${t}`).join('\n');
        const bonus = rubric.deductionRules?.bonusRules
            ? `Бонус: ${rubric.deductionRules.bonusRules.description}. Поле bonus_awarded — от 0 до ${rubric.deductionRules.bonusRules.maxBonus}, с обоснованием ПО-ВЬЕТНАМСКИ в bonus_reason_vi.`
            : 'На этом уровне бонусных баллов НЕТ: bonus_awarded = 0, bonus_reason_vi = "".';
        return `${head}

МЕХАНИЗМ: прямое снятие баллов со шкалы ${rubric.totalScore} баллов.
Ты НЕ считаешь баллы сам — систему подсчёта выполняет сервер
(каждая КЗО −${rubric.deductionRules.kzoPenalty}, каждая КНЗО −${rubric.deductionRules.knzoPenalty}).
Твоя работа — правильно классифицировать каждую ошибку.
${extra ? `\nДополнительные требования ${rubric.trkiName}:\n${extra}` : ''}
${bonus}
parameter_scores на этом уровне оставь ПУСТЫМ массивом — официальная шкала ${rubric.trkiName}
не выставляет отдельные баллы по критериям, и выдумывать их нельзя.

ВМЕСТО баллов заполни criteria_notes — качественный разбор по критериям.
Ровно эти четыре критерия, именно в таком виде и в таком порядке:
- «Содержание» — раскрыта ли тема, есть ли все нужные смысловые части;
- «Композиция и связность» — членение на абзацы, логика, средства связи;
- «Грамматика и орфография» — какие нарушения нормы преобладают;
- «Лексика» — точность словоупотребления, богатство, сочетаемость.
Для каждого: verdict («хорошо» / «нормально» / «слабо»), comment_vi — по-вьетнамски,
с опорой на конкретные места текста, и improve_vi — по-вьетнамски, что именно делать дальше.
Формулировка вида «нужно писать грамотнее» запрещена: пиши, ЧТО и КАК.`;
    }

    const params = rubric.parameters.map(p => `- ${p.name} (0–${p.maxScore}): ${p.description}`).join('\n');
    const reqs = (rubric.essayRequirements || []).length
        ? `\nОБЯЗАТЕЛЬНЫЕ СОДЕРЖАТЕЛЬНЫЕ КОМПОНЕНТЫ ЭССЕ — проверь каждый и заполни essay_requirements_check (note_vi — по-вьетнамски):\n${rubric.essayRequirements.map(r => `- ${r}`).join('\n')}`
        : '\nessay_requirements_check оставь пустым массивом.';
    return `${head}

МЕХАНИЗМ: оценка по параметрам. Выстави «сырой» балл каждому параметру:
${params}
Ограничение баллов при наличии КЗО применяет сервер — ты его НЕ применяешь.
bonus_awarded = 0, bonus_reason_vi = "". criteria_notes оставь ПУСТЫМ массивом.

ПО КАЖДОМУ ПАРАМЕТРУ обязательно заполни ЧЕТЫРЕ поля:
- score — сырой балл;
- comment_vi — ПО-ВЬЕТНАМСКИ: почему именно этот балл, со ссылкой на конкретные
  места текста. Не «có một số lỗi ngữ pháp», а «cách dùng cách 4 sau "защищать"
  sai ở hai chỗ, làm câu thứ hai của đoạn 2 khó hiểu»;
- strength_vi — ПО-ВЬЕТНАМСКИ: что по этому параметру уже получается;
- improve_vi — ПО-ВЬЕТНАМСКИ: конкретное действие, чтобы поднять балл.
Балл и comment_vi не должны противоречить друг другу: 5 из 5 при списке проблем
в комментарии — это ошибка оценивания.${reqs}`;
}

